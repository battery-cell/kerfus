#!/usr/bin/env python3
"""Generate a clean reference map of worlds/room.sdf for the Nav2 demo.

    python3 maps/generate_room_map.py

Writes room.pgm and room.yaml next to this script. The map uses the same
coordinates as the Gazebo world: 0.05 m per pixel, origin at (-3.3, -2.8), and
the robot spawns at world (0, 0), which is free space in the map.

This is a hand-generated map for teaching/navigation. The SLAM demo
(bringup.launch.py) builds its own map from the simulated lidar instead.
"""
import math
from pathlib import Path

# --- map grid -------------------------------------------------------------
RESOLUTION = 0.05
ORIGIN_X, ORIGIN_Y = -3.3, -2.8
WIDTH_M, HEIGHT_M = 6.6, 5.6
WIDTH = round(WIDTH_M / RESOLUTION)     # 132 pixels
HEIGHT = round(HEIGHT_M / RESOLUTION)   # 112 pixels

FREE = 254
OCCUPIED = 0
UNKNOWN = 205

# --- world geometry (from worlds/room.sdf) --------------------------------
ROOM_X = (-3.0, 3.0)
ROOM_Y = (-2.5, 2.5)

# (centre x, centre y, size x, size y, yaw)
RECTANGLES = [
    # walls
    (0.0,  2.55, 6.2, 0.1, 0.0),
    (0.0, -2.55, 6.2, 0.1, 0.0),
    (3.05,  0.0, 0.1, 5.0, 0.0),
    (-3.05, 0.0, 0.1, 5.0, 0.0),
    # crate and table
    (1.5, 1.0, 0.5, 0.5, 0.3),
    (-1.0, 1.7, 1.0, 0.5, 0.0),
]

# (centre x, centre y, radius)
CIRCLES = [
    (-1.5, -1.0, 0.2),  # pillar
]


def cell_centre(col, row):
    """World coordinates of the centre of pixel (col, row)."""
    x = ORIGIN_X + (col + 0.5) * RESOLUTION
    y = ORIGIN_Y + (HEIGHT - 1 - row + 0.5) * RESOLUTION
    return x, y


def inside_rectangle(x, y, cx, cy, sx, sy, yaw):
    dx, dy = x - cx, y - cy
    c, s = math.cos(yaw), math.sin(yaw)
    local_x = c * dx + s * dy
    local_y = -s * dx + c * dy
    return abs(local_x) <= sx / 2.0 and abs(local_y) <= sy / 2.0


def occupancy(col, row):
    x, y = cell_centre(col, row)

    if ROOM_X[0] <= x <= ROOM_X[1] and ROOM_Y[0] <= y <= ROOM_Y[1]:
        value = FREE
    else:
        value = UNKNOWN

    for cx, cy, sx, sy, yaw in RECTANGLES:
        if inside_rectangle(x, y, cx, cy, sx, sy, yaw):
            return OCCUPIED

    for cx, cy, radius in CIRCLES:
        if math.hypot(x - cx, y - cy) <= radius:
            return OCCUPIED

    return value


def main():
    here = Path(__file__).resolve().parent
    pixels = bytearray()
    for row in range(HEIGHT):
        for col in range(WIDTH):
            pixels.append(occupancy(col, row))

    pgm_path = here / 'room.pgm'
    with open(pgm_path, 'wb') as f:
        f.write(f'P5\n{WIDTH} {HEIGHT}\n255\n'.encode('ascii'))
        f.write(pixels)

    yaml_path = here / 'room.yaml'
    yaml_path.write_text(
        '# Reference map generated by generate_room_map.py from worlds/room.sdf.\n'
        'image: room.pgm\n'
        'mode: trinary\n'
        f'resolution: {RESOLUTION}\n'
        f'origin: [{ORIGIN_X}, {ORIGIN_Y}, 0.0]\n'
        'negate: 0\n'
        'occupied_thresh: 0.65\n'
        'free_thresh: 0.19\n'
    )

    print(f'wrote {pgm_path} ({WIDTH} x {HEIGHT}) and {yaml_path}')


if __name__ == '__main__':
    main()
